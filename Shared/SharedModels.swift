import SwiftUI

// MARK: - Subway Line Model

struct SubwayLine: Identifiable, Equatable, Hashable {
    let id: String
    let label: String
    let bg_color: Color
    let fg_color: Color

    func hash(into hasher: inout Hasher) {
        hasher.combine(id)
    }

    static func == (lhs: SubwayLine, rhs: SubwayLine) -> Bool {
        return lhs.id == rhs.id
    }
}

// MARK: - Station Model

struct Station: Identifiable, Codable, Equatable {
    let id: String
    let display: String
    let name: String
    /// GTFS parent stop ID (without direction suffix), e.g. "127" for Times Square
    /// on the 1/2/3 platforms.  Append "N" or "S" to get the directional stop ID
    /// used in GTFS-RT feeds.
    ///
    /// Populate this field by running `scripts/generate_gtfs_mapping.py` against
    /// the MTA's GTFS static data.  Stations without this value cannot be looked
    /// up in the GTFS-RT feed.
    var gtfsStopId: String?
    /// WGS-84 latitude from MTA GTFS `stops.txt`.  Required for the nearby-trains feature.
    var latitude: Double?
    /// WGS-84 longitude from MTA GTFS `stops.txt`.  Required for the nearby-trains feature.
    var longitude: Double?
    /// MTA complex ID grouping platforms that share an underground connection.
    /// Derived from the MTA's Stations.csv open data file via generate_gtfs_mapping.py.
    /// Used by the nearby view to merge same-complex platforms into one section.
    var complexId: String?
    /// When the line is scheduled to stop here, for stations it doesn't serve
    /// around the clock: New York hours by day, like `["mon": "0-6,19-23"]`,
    /// with days it doesn't stop left out. Nil means every hour. Generated by
    /// scripts/generate_service_hours.py.
    var serviceHours: [String: String]?
    /// When the line's trains end here though the list runs on, by direction ("N" or "S"),
    /// in the same form as `serviceHours`: the 4 at Crown Heights-Utica Av by day, say.
    var terminalHours: [String: [String: String]]?
    var hasAvailableTimes: Bool?

    init(
        id: String = UUID().uuidString,
        display: String,
        name: String,
        gtfsStopId: String? = nil,
        latitude: Double? = nil,
        longitude: Double? = nil,
        complexId: String? = nil,
        serviceHours: [String: String]? = nil,
        terminalHours: [String: [String: String]]? = nil,
        hasAvailableTimes: Bool? = nil
    ) {
        self.id = id
        self.display = display
        self.name = name
        self.gtfsStopId = gtfsStopId
        self.latitude = latitude
        self.longitude = longitude
        self.complexId = complexId
        self.serviceHours = serviceHours
        self.terminalHours = terminalHours
        self.hasAvailableTimes = hasAvailableTimes
    }

    private enum CodingKeys: String, CodingKey {
        case display
        case name
        case gtfsStopId
        case latitude
        case longitude
        case complexId
        case serviceHours
        case terminalHours
        case hasAvailableTimes
        // "id" is intentionally omitted — it is derived from `name` on decode.
    }

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        self.display = try container.decode(String.self, forKey: .display)
        self.name = try container.decode(String.self, forKey: .name)
        self.gtfsStopId = try container.decodeIfPresent(String.self, forKey: .gtfsStopId)
        self.latitude = try container.decodeIfPresent(Double.self, forKey: .latitude)
        self.longitude = try container.decodeIfPresent(Double.self, forKey: .longitude)
        self.complexId = try container.decodeIfPresent(String.self, forKey: .complexId)
        self.serviceHours = try container.decodeIfPresent([String: String].self, forKey: .serviceHours)
        self.terminalHours = try container.decodeIfPresent([String: [String: String]].self, forKey: .terminalHours)
        self.hasAvailableTimes = try container.decodeIfPresent(Bool.self, forKey: .hasAvailableTimes)
        self.id = name  // stable, name-based ID
    }

    func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
        try container.encode(display, forKey: .display)
        try container.encode(name, forKey: .name)
        try container.encodeIfPresent(gtfsStopId, forKey: .gtfsStopId)
        try container.encodeIfPresent(latitude, forKey: .latitude)
        try container.encodeIfPresent(longitude, forKey: .longitude)
        try container.encodeIfPresent(complexId, forKey: .complexId)
        try container.encodeIfPresent(serviceHours, forKey: .serviceHours)
        try container.encodeIfPresent(terminalHours, forKey: .terminalHours)
        try container.encodeIfPresent(hasAvailableTimes, forKey: .hasAvailableTimes)
    }
}

extension Station {
    // Indexed by Calendar's weekday, 1 = Sunday
    private static let serviceDays = ["sun", "mon", "tue", "wed", "thu", "fri", "sat"]

    private static let newYorkCalendar: Calendar = {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "America/New_York")!
        return calendar
    }()

    /// Whether the line is scheduled to stop here at `date`, by New York time
    /// wherever the device is.
    func isScheduled(at date: Date = Date()) -> Bool {
        guard let serviceHours else { return true }
        return Self.hours(serviceHours, include: date)
    }

    /// Whether the line's trains in `direction` ("N" or "S") end here at `date`, though the
    /// list runs on past it.
    func isTerminal(direction: String, at date: Date = Date()) -> Bool {
        guard let hours = terminalHours?[direction] else { return false }
        return Self.hours(hours, include: date)
    }

    /// Whether New York's hour at `date` falls in `hours`, like `["mon": "0-6,19-23"]`.
    private static func hours(_ hours: [String: String], include date: Date) -> Bool {
        let parts = newYorkCalendar.dateComponents([.weekday, .hour], from: date)
        guard let weekday = parts.weekday, let hour = parts.hour,
              let ranges = hours[serviceDays[weekday - 1]] else { return false }
        return ranges.split(separator: ",").contains { range in
            let bounds = range.split(separator: "-").compactMap { Int($0) }
            guard let start = bounds.first, let end = bounds.last else { return false }
            return start <= hour && hour <= end
        }
    }
}
